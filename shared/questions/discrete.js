function graph(int) {
  const a = Array.from({ length: 5 }, () => Array(5).fill(0));
  for (let i = 0; i < 5; i++)
    for (let j = i + 1; j < 5; j++)
      if (j === i + 1 || int(0, 1)) a[i][j] = a[j][i] = 1;
  return a;
}
function traversal(a, dfs = false) {
  const seen = new Set(),
    order = [];
  const visit = (v) => {
    seen.add(v);
    order.push(v);
    for (let w = 0; w < a.length; w++) if (a[v][w] && !seen.has(w)) visit(w);
  };
  if (dfs) visit(0);
  else {
    const q = [0];
    seen.add(0);
    for (let k = 0; k < q.length; k++) {
      const v = q[k];
      order.push(v);
      for (let w = 0; w < a.length; w++)
        if (a[v][w] && !seen.has(w)) {
          seen.add(w);
          q.push(w);
        }
    }
  }
  return order;
}
